#!/usr/bin/env python3
"""Generate the Argo CD Application manifest for the practice app.

Argo reads the in-cluster git server when it exists and GitHub otherwise. Either
way the URL is derived, never committed, so nothing user-specific lands in git.
Works the same on Linux, WSL, and Windows (any Python 3.9+).

Output: argocd/generated/practice-app.yaml  (git-ignored)
Apply:  make app-deploy   (or kubectl apply -f argocd/generated/practice-app.yaml)
"""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_argocd_app_url import repo_https_url

REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "argocd" / "generated"


def source_repo_url() -> str:
    """Argo reads cluster git when it exists, GitHub otherwise.

    One Application, permanently. Cluster git is the source; GitHub is the upstream
    the workspace pushes to. Falling back keeps the toggle honest: with
    enable_cluster_git = false everything behaves exactly as it did before.

    The fallback is not a hole in the self-contained git rule. It is the pre-drill
    path, reached only when the toggle is off, which is how this repo behaved for
    everyone before the drill existed. On the drill path the toggle is on and the
    fallback is unreachable. What the rule forbids is Argo reading GitHub while a
    drill is running, and that cannot happen here.
    """
    out = subprocess.run(
        [sys.executable, str(REPO / "scripts" / "bootstrap.py"),
         "dev", "output", "-raw", "cluster_git_url"],
        capture_output=True,
        text=True,
    )
    url = out.stdout.strip() if out.returncode == 0 else ""
    if url:
        print(f"gen-argocd-app: pointing Argo CD at cluster git ({url})", file=sys.stderr)
        return url
    print("gen-argocd-app: cluster git is off - pointing Argo CD at GitHub", file=sys.stderr)
    return repo_https_url()


def main() -> int:
    url = source_repo_url()
    manifest = f"""# Generated by scripts/gen-argocd-app.py - do not edit, do not commit.
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: practice-app
  namespace: argocd
spec:
  project: default
  source:
    repoURL: {url}
    targetRevision: main
    path: helm/practice-app
  destination:
    server: https://kubernetes.default.svc
    namespace: practice-app
  # Sync is MANUAL on purpose - pressing the button (and turning on automation)
  # is part of the GitOps scenario.
  syncPolicy:
    syncOptions:
      - CreateNamespace=false
"""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / "practice-app.yaml"
    out.write_text(manifest)
    print(f"gen-argocd-app: wrote {out.relative_to(REPO)} (repoURL: {url})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
